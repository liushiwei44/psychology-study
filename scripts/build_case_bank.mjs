const cases = [];
function add(id, subject, topic, title, material, rows) {
  cases.push({ id, subject, topic, title, material, questions: rows.map(([stem, options, answer, explanation], i) => {
    // Rotate option positions so authored examples do not teach a fixed answer position.
    const shift = (cases.length + i) % 4;
    const keys = 'ABCD';
    const rotated = options.slice(shift).concat(options.slice(0, shift));
    const correct = [...answer].map((key) => keys[(keys.indexOf(key) - shift + 4) % 4]).sort().join('');
    return { id: `${id}-${String(i + 1).padStart(2, '0')}`, type: i < 5 ? 'case_single' : 'case_multiple', stem,
      options: rotated.map((text, n) => ({ key: keys[n], text })), answer: correct, explanation };
  }) });
}
